const swiper = new Swiper(".projectsSwiper", {

    /*
     * Default: Mobile
     * One slide visible
     */
    slidesPerView: 1,

    /*
     * Move only ONE item at a time
     */
    slidesPerGroup: 1,

    /*
     * Space between slides
     */
    spaceBetween: 15,


    /*
     * Navigation arrows
     */
    navigation: {

      nextEl: ".swiper-button-next",

      prevEl: ".swiper-button-prev"

    },


    /*
     * Pagination dots
     */
    pagination: {

      el: ".swiper-pagination",

      clickable: true

    },


    /*
     * Touch/swipe is enabled by default
     */


    /*
     * Responsive settings
     */
    breakpoints: {

      /*
       * Tablet
       * 768px and above
       */
      768: {

        slidesPerView: 2,

        slidesPerGroup: 1,

        spaceBetween: 20

      },


      /*
       * Large screens
       * 992px and above
       */
      992: {

        slidesPerView: 3,

        slidesPerGroup: 1,

        spaceBetween: 20

      }

    }

  });

